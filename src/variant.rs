//! Rust translation of `src/Variant.h` / `src/Variant.cpp`.
//!
//! [`Variant`] is the dynamically typed value of the expression evaluator
//! (`Eval`): a tagged union over Boolean, integer, real, string, date and
//! duration, with every C++ member kept under its C++ name (`_type`,
//! `_bool`, ...).
//!
//! # File layout
//! The file follows Variant.cpp function by function, separated by the C++
//! `////...` rules:
//! 1. error message texts, statics, constructors, `source`;
//! 2. the operators (`operator&&` .. `operator%`, Variant.cpp lines
//!    148-1860), which are ported in that order directly after `source`;
//! 3. `operator std::string` ([`fmt::Display`]), `sqrt`, `cast`, `type`,
//!    `trivial` and the getters.
//!
//! # API mapping
//! * Constructors: `Variant (bool)` -> [`Variant::from_bool`], `(int)` ->
//!   [`Variant::from_int`], `(double)` -> [`Variant::from_real`],
//!   `(const std::string&)` / `(const char*)` -> [`Variant::from_string`],
//!   `(time_t, type)` -> [`Variant::from_time`] (fallible, as the C++
//!   throws). `From<bool|i32|f64|&str|String>` are provided too.
//!   `Variant ()` is `Default` (Boolean `false`); copy construction and
//!   `operator=` are `Clone`.
//! * `throw std::string (...)` becomes `Err (TwError::Message (...))` with
//!   the identical text; `cast` and `sqrt` therefore return `Result`.
//! * Statics (`dateFormat`, `searchCaseSensitive`, `searchUsingRegex`,
//!   `isoEnabled`) are thread-local getter/setter pairs (wiki "Process-wide
//!   statics").
//! * Operators are methods named `op_<name>`: `operator&&` -> `op_and`,
//!   `operator||` -> `op_or`, `operator_xor` -> `op_xor`, `operator<` /
//!   `<=` / `>` / `>=` -> `op_lt` / `op_lte` / `op_gt` / `op_gte`,
//!   `operator==` / `!=` -> `op_eq` / `op_ne`, `operator!` -> `op_not`.
//!   The C++ returns `bool`; the comparisons return `Result<bool>` because
//!   their string to date casts can throw. They are not `PartialEq` /
//!   `PartialOrd` impls, since those cannot be fallible.
//! * Arithmetic: `operator^=` / `^` -> `op_exp_assign` / `op_exp`,
//!   `operator-=` / `-` -> `op_sub_assign` / `op_sub`, `operator+=` / `+` ->
//!   `op_add_assign` / `op_add`. The compound forms return `Result<()>`
//!   (C++ returns `*this`), the binary forms `Result<Variant>`; they are not
//!   `std::ops` impls because the C++ throws.
//! * `Task::customOrder` (read by the ordering operators) is defined here
//!   until the Task port, see [`Task::custom_order`].
//! * The `Task&` parameters of `operator_match` / `operator_hastag` are
//!   abstracted by [`VariantTask`].

