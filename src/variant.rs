/// C++ `Variant::operator std::string () const`.
impl fmt::Display for Variant {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self._type {
            Type::Boolean => f.write_str(if self._bool { "true" } else { "false" }),

            // std::stringstream s; s << _integer;
            Type::Integer => write!(f, "{}", self._integer),

            // std::stringstream s; s << _real;
            Type::Real => f.write_str(&stream_double(self._real)),

            Type::String => f.write_str(&self._string),

            Type::Date => f.write_str(&Datetime::from_epoch(self._date).to_iso_local_extended()),

            Type::Duration => f.write_str(&Duration::from_seconds(self._duration).format_iso()),
        }
    }
}

