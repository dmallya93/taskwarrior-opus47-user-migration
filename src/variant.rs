// C library helpers.

/// `text` as a C string, truncated at the first NUL like `c_str ()`.
fn c_string(text: &str) -> CString {
    let text = text.find('\0').map_or(text, |nul| &text[..nul]);
    CString::new(text).unwrap_or_default()
}

/// C `strtol (s.c_str (), nullptr, base)` through libc (`long` is 64-bit on
/// the supported LP64 targets), so whitespace, sign, `0x` prefix and
/// saturation behave identically.
fn c_strtol(text: &str, base: i32) -> i64 {
    let text = c_string(text);
    // SAFETY: `text` is a valid NUL-terminated string and a null `endptr` is
    // permitted.
    unsafe { libc::strtol(text.as_ptr(), std::ptr::null_mut(), base) }
}

/// C `strtod (s.c_str (), nullptr)` through libc (decimal, exponent, hex,
/// `inf`, `nan`; the process never calls `setlocale`, so the radix is `.`).
fn c_strtod(text: &str) -> f64 {
    let text = c_string(text);
    // SAFETY: as in `c_strtol`.
    unsafe { libc::strtod(text.as_ptr(), std::ptr::null_mut()) }
}

/// C++ `(long long) value`.
///
/// Deviation: out-of-range and NaN conversions are undefined in C++; this
/// reproduces the x86-64 `cvttsd2si` result the reference binary produces
/// (the "integer indefinite" `LLONG_MIN`) instead of Rust's saturation.
fn c_double_to_long_long(value: f64) -> i64 {
    if value.is_nan() || !(-9_223_372_036_854_775_808.0..9_223_372_036_854_775_808.0).contains(&value) {
        i64::MIN
    } else {
        value as i64
    }
}

/// C++ `(int) value`.
///
/// Deviation: as [`c_double_to_long_long`], out-of-range and NaN give the
/// x86-64 32-bit `cvttsd2si` result `INT_MIN`.
fn c_double_to_int(value: f64) -> i32 {
    if value.is_nan() || value <= -2_147_483_649.0 || value >= 2_147_483_648.0 {
        i32::MIN
    } else {
        value as i32
    }
}

