/// C++ `widechar_in_table`: `std::lower_bound` on `hi`, then check `lo`.
fn widechar_in_table(arr: &[WidecharRange], c: u32) -> bool {
    let where_ = arr.partition_point(|p| p.hi < c);
    where_ != arr.len() && arr[where_].lo <= c
}

/// C++ `widechar_wcwidth`: return the width of character `c`, or a special
/// negative value.
pub fn widechar_wcwidth(c: u32) -> i32 {
    if widechar_in_table(WIDECHAR_ASCII_TABLE, c) {
        return 1;
    }
    if widechar_in_table(WIDECHAR_PRIVATE_TABLE, c) {
        return WIDECHAR_PRIVATE_USE;
    }
    if widechar_in_table(WIDECHAR_NONPRINT_TABLE, c) {
        return WIDECHAR_NONPRINT;
    }
    if widechar_in_table(WIDECHAR_COMBINING_TABLE, c) {
        return WIDECHAR_COMBINING;
    }
    if widechar_in_table(WIDECHAR_DOUBLEWIDE_TABLE, c) {
        return 2;
    }
    if widechar_in_table(WIDECHAR_AMBIGUOUS_TABLE, c) {
        return WIDECHAR_AMBIGUOUS;
    }
    if widechar_in_table(WIDECHAR_UNASSIGNED_TABLE, c) {
        return WIDECHAR_UNASSIGNED;
    }
    if widechar_in_table(WIDECHAR_WIDENED_TABLE, c) {
        return WIDECHAR_WIDENED_IN_9;
    }
    1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_disjoint() {
        for table in [
            WIDECHAR_ASCII_TABLE,
            WIDECHAR_PRIVATE_TABLE,
            WIDECHAR_NONPRINT_TABLE,
            WIDECHAR_COMBINING_TABLE,
            WIDECHAR_DOUBLEWIDE_TABLE,
            WIDECHAR_AMBIGUOUS_TABLE,
            WIDECHAR_UNASSIGNED_TABLE,
            WIDECHAR_WIDENED_TABLE,
        ] {
            for pair in table.windows(2) {
                assert!(pair[0].lo <= pair[0].hi);
                assert!(pair[0].hi < pair[1].lo);
            }
        }
    }

    #[test]
    fn classification() {
        assert_eq!(widechar_wcwidth('a' as u32), 1);
        assert_eq!(widechar_wcwidth(0x0A), WIDECHAR_NONPRINT);
        assert_eq!(widechar_wcwidth(0x0301), WIDECHAR_COMBINING);
        assert_eq!(widechar_wcwidth(0x4E00), 2);
        assert_eq!(widechar_wcwidth(0x00C7), 1);
        assert_eq!(widechar_wcwidth(0x00A1), WIDECHAR_AMBIGUOUS);
        assert_eq!(widechar_wcwidth(0xE000), WIDECHAR_PRIVATE_USE);
        assert_eq!(widechar_wcwidth(0x0378), WIDECHAR_UNASSIGNED);
        assert_eq!(widechar_wcwidth(0x1F004), WIDECHAR_WIDENED_IN_9);
    }
}
